def build_datasets():
    out_dir = Path("d:/projects/poc/ai_ops/data")
    out_dir.mkdir(parents=True, exist_ok=True)
    
    # Save pass 2 verified
    pass2_file = out_dir / "pass2_verified.json"
    pass2_file.write_text(json.dumps(APPS_RESEARCH_DATA, indent=2), encoding="utf-8")
    print(f"Wrote {len(APPS_RESEARCH_DATA)} verified records to {pass2_file}")

    # Save pass 1 raw (baseline before verification corrections)
    pass1_data = []
    for app in APPS_RESEARCH_DATA:
        item = dict(app)
        if item.get("verification_status") == "Corrected & Enhanced":
            # Simulate initial raw state before Pass 2 critic
            item["confidence_score"] = 65
            item["verification_status"] = "Unverified Initial Pass"
        pass1_data.append(item)
        
    pass1_file = out_dir / "pass1_research_raw.json"
    pass1_file.write_text(json.dumps(pass1_data, indent=2), encoding="utf-8")
    print(f"Wrote Pass 1 raw records to {pass1_file}")

if __name__ == "__main__":
    build_datasets()
